#!/usr/bin/env python3
"""One release number for the web console and both active firmware roles."""
import argparse
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--set', metavar='X.Y.Z')
p.add_argument('--check', action='store_true')
a = p.parse_args()
manifest = json.loads((root / 'version.json').read_text())
if a.set:
    if not re.fullmatch(r'0|[1-9]\d*', a.set.split('.')[0]) or not re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)', a.set):
        p.error('Use X.Y.Z with no leading zeroes')
    manifest['version'] = a.set
    (root / 'version.json').write_text(json.dumps(manifest, indent=2) + '\n')
v = manifest['version']
expected = {
    root / 'console/release.h': f'#pragma once\n// Generated by tools/release.py from version.json\n#define THEATRE_NAME "{manifest["name"]}"\n#define THEATRE_VERSION "{v}"\n',
    root / 'score-ui/src/version.ts': f'// Generated by tools/release.py from version.json\nexport const INTERFACE_VERSION = \'{v}\';\nexport const PRODUCT_NAME = \'{manifest["name"]}\';\n',
}
for name in ('package.json', 'package-lock.json'):
    path = root / 'score-ui' / name
    text = path.read_text()
    # Root versions only; dependency versions must never be changed.
    text = re.sub(r'("version":\s*")[^"]+', lambda m: m[1] + v, text, count=2 if name == 'package-lock.json' else 1)
    expected[path] = text
for path, text in expected.items():
    if a.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f'Version mismatch: {path.relative_to(root)}; run python3 tools/release.py')
    else:
        path.write_text(text)
print(f'{manifest["name"]} {v}: web/master/slave synchronized')
